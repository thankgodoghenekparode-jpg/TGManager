// ==================== API ====================

export interface CbtImportIssue {
  line: number;
  column?: string;
  message: string;
}

export interface CbtImportResult {
  dryRun: boolean;
  created: number;
  errors: CbtImportIssue[];
  preview: Array<{
    line: number;
    subject: string;
    category: string;
    difficulty: string;
    question: string;
    options: string[];
    correctIndex: number;
    source: string;
  }>;
}

export const cbtApi = {
  // Dashboard & reports
  dashboard: () => api.get<CbtDashboard>('/school/cbt/reports/dashboard').then((r) => r.data),
  myAttempts: (params?: { examId?: string; limit?: number }) =>
    api
      .get<{ items: CbtAttemptHistoryItem[]; total: number; limit: number }>(
        '/school/cbt/reports/my-attempts',
        { params },
      )
      .then((r) => r.data),
  examReport: (params: {
    examId: string;
    classId?: string;
    studentId?: string;
    page?: number;
    limit?: number;
  }) => api.get<CbtExamReport>('/school/cbt/reports/exam', { params }).then((r) => r.data),
  performance: (params?: {
    classId?: string;
    subjectId?: string;
    studentId?: string;
    limit?: number;
  }) =>
    api.get<CbtPerformanceReport>('/school/cbt/reports/performance', { params }).then((r) => r.data),

  // Question bank
  listQuestions: (params?: {
    subjectId?: string;
    category?: CbtCategory;
    difficulty?: CbtDifficulty;
    status?: CbtQuestionStatus;
    source?: CbtQuestionSource;
    search?: string;
    page?: number;
    limit?: number;
  }) =>
    api
      .get<{ items: CbtQuestion[]; total: number; page: number; limit: number }>(
        '/school/cbt/questions',
        { params },
      )
      .then((r) => r.data),
  questionSummary: () =>
    api.get<CbtQuestionSummary>('/school/cbt/questions/summary').then((r) => r.data),
  getQuestion: (id: string) =>
    api.get<CbtQuestion>(`/school/cbt/questions/${id}`).then((r) => r.data),
  createQuestion: (data: Record<string, unknown>) =>
    api.post<CbtQuestion>('/school/cbt/questions', data).then((r) => r.data),
  updateQuestion: (id: string, data: Record<string, unknown>) =>
    api.patch<CbtQuestion>(`/school/cbt/questions/${id}`, data).then((r) => r.data),
  archiveQuestion: (id: string) =>
    api.post(`/school/cbt/questions/${id}/archive`).then((r) => r.data),
  restoreQuestion: (id: string) =>
    api.post(`/school/cbt/questions/${id}/restore`).then((r) => r.data),
  questionTemplate: () =>
    api
      .get<{ template: string; columns: string[]; notes: string[] }>(
        '/school/cbt/questions/template',
      )
      .then((r) => r.data),
  previewImport: (csv: string) =>
    api
      .post<CbtImportResult>('/school/cbt/questions/import/preview', { csv, dryRun: true })
      .then((r) => r.data),
  commitImport: (csv: string) =>
    api
      .post<CbtImportResult>('/school/cbt/questions/import', { csv, dryRun: false })
      .then((r) => r.data),

  // Exams (staff)
  listExams: (params?: {
    status?: CbtExamStatus;
    category?: CbtCategory;
    mode?: CbtExamMode;
    classId?: string;
    subjectId?: string;
    search?: string;
    page?: number;
    limit?: number;
  }) =>
    api
      .get<{ items: CbtExamSummary[]; total: number; page: number; limit: number }>(
        '/school/cbt/exams',
        { params },
      )
      .then((r) => r.data),
  getExam: (id: string) => api.get<CbtExamDetail>(`/school/cbt/exams/${id}`).then((r) => r.data),
  createExam: (data: Record<string, unknown>) =>
    api.post<CbtExamDetail>('/school/cbt/exams', data).then((r) => r.data),
  updateExam: (id: string, data: Record<string, unknown>) =>
    api.patch<CbtExamDetail>(`/school/cbt/exams/${id}`, data).then((r) => r.data),
  assignExam: (id: string, data: { classId?: string | null; studentIds?: string[]; replace?: boolean }) =>
    api.post(`/school/cbt/exams/${id}/assign`, data).then((r) => r.data),
  deleteExam: (id: string) =>
    api.delete<{ success: boolean; action: 'deleted' | 'archived' }>(`/school/cbt/exams/${id}`).then((r) => r.data),

  // Exams (student)
  availableExams: () =>
    api.get<CbtStudentExam[]>('/school/cbt/exams/available').then((r) => r.data),
  examBrief: (id: string) =>
    api.get<CbtExamBrief>(`/school/cbt/exams/${id}/brief`).then((r) => r.data),

  // Attempts
  startAttempt: (examId: string) =>
    api.post<CbtAttemptResponse>('/school/cbt/attempts/start', { examId }).then((r) => r.data),
  getAttempt: (attemptId: string) =>
    api.get<CbtAttemptResponse>(`/school/cbt/attempts/${attemptId}`).then((r) => r.data),
  saveAnswers: (
    attemptId: string,
    answers: Array<{ questionId: string; selectedOptionId: string | null; markedForReview: boolean }>,
  ) =>
    api
      .post<CbtSaveReceipt>(`/school/cbt/attempts/${attemptId}/answers`, { answers })
      .then((r) => r.data),
  submitAttempt: (attemptId: string, auto = false) =>
    api
      .post<CbtResultPayload>(`/school/cbt/attempts/${attemptId}/submit`, { auto })
      .then((r) => r.data),
};

export type CbtApi = typeof cbtApi;
