import { api } from './client';

// ==================== Shared vocab ====================

export type CbtCategory = 'JAMB' | 'WAEC' | 'NECO' | 'SCHOOL' | 'MOCK' | 'GENERAL';
export type CbtExamMode = 'PRACTICE' | 'MOCK';
export type CbtExamStatus = 'DRAFT' | 'PUBLISHED' | 'ARCHIVED';
export type CbtQuestionSource = 'SCHOOL' | 'TGMANAGER' | 'LICENSED' | 'AI';
export type CbtDifficulty = 'EASY' | 'MEDIUM' | 'HARD';
export type CbtQuestionStatus = 'DRAFT' | 'ACTIVE' | 'ARCHIVED';
export type CbtAttemptStatus = 'IN_PROGRESS' | 'SUBMITTED' | 'EXPIRED';

export const CBT_CATEGORY_LABELS: Record<CbtCategory, string> = {
  JAMB: 'JAMB Practice',
  WAEC: 'WAEC Practice',
  NECO: 'NECO Practice',
  SCHOOL: 'School CBT',
  MOCK: 'Mock Examinations',
  GENERAL: 'General Practice',
};

export const CBT_SOURCE_LABELS: Record<CbtQuestionSource, string> = {
  SCHOOL: 'School-created',
  TGMANAGER: 'TGManager-created',
  LICENSED: 'Licensed / Imported',
  AI: 'AI-generated (practice)',
};

export const CBT_PLATFORM_NOTICE =
  'TGManager is an independent practice platform. It is not affiliated with, and does not reproduce, official JAMB, WAEC or NECO question papers.';

export const AI_QUESTION_NOTICE =
  'Practice question generated by AI — not an authentic past examination question.';

// ==================== Interfaces ====================

export interface CbtSubject {
  id: string;
  code: string;
  name: string;
}

export interface CbtOption {
  id: string;
  label: string;
  text: string;
  isCorrect?: boolean;
}

export interface CbtQuestion {
  id: string;
  text: string;
  imageUrl?: string | null;
  category: CbtCategory;
  difficulty: CbtDifficulty;
  marks: number;
  source: CbtQuestionSource;
  status: CbtQuestionStatus;
  explanation?: string | null;
  topicId?: string | null;
  topicName?: string | null;
  topic?: { id: string; name: string } | null;
  subject?: CbtSubject | null;
  options: CbtOption[];
  createdBy?: { id: string; firstName: string; lastName: string } | null;
  _count?: { attemptAnswers: number };
  createdAt: string;
  updatedAt: string;
}

export interface CbtQuestionSummary {
  total: number;
  active: number;
  draft: number;
  archived: number;
  byDifficulty: { EASY: number; MEDIUM: number; HARD: number };
  subjects: CbtSubject[];
}

export interface CbtExamSummary {
  id: string;
  title: string;
  category: CbtCategory;
  mode: CbtExamMode;
  status: CbtExamStatus;
  description?: string | null;
  durationMinutes: number;
  totalMarks: number;
  passMark: number;
  maxAttempts: number;
  startAt?: string | null;
  endAt?: string | null;
  subject?: CbtSubject | null;
  class?: { id: string; name: string } | null;
  createdBy?: { id: string; firstName: string; lastName: string } | null;
  _count?: { questions: number; attempts: number; assignments: number };
  createdAt: string;
}

export interface CbtExamDetail extends CbtExamSummary {
  instructions?: string | null;
  randomizeQuestions: boolean;
  randomizeOptions: boolean;
  showResultImmediately: boolean;
  showCorrectAnswers: boolean;
  negativeMarking: boolean;
  negativeMarkPerWrong: number;
  questions: Array<{
    order: number;
    marks: number;
    question: {
      id: string;
      text: string;
      difficulty: CbtDifficulty;
      category: CbtCategory;
      marks: number;
      status: CbtQuestionStatus;
      subject?: CbtSubject | null;
      options: CbtOption[];
    };
  }>;
  assignments: Array<{
    id: string;
    class?: { id: string; name: string } | null;
    student?: {
      id: string;
      firstName: string;
      lastName: string;
      admissionNumber: string;
    } | null;
  }>;
}

